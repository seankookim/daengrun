// 코스 이름을 화면에 쓸 때의 한 가지 규칙.
//
// ═══ 왜 필요한가 (2026-08-14, 시뮬레이터에서 측정) ═══
// `routes.name`에 길이가 박혀 있는 행이 많다: `한강 반포–잠원 7km`, `잠원 한신2차 리버 루프
// 2.78km`, `이촌 가족공원 루프 5.05km`. 그런데 화면은 그 옆에 `km` 컬럼을 따로 그린다. 결과는
// 같은 양에 대한 **두 개의 숫자**이고, 둘은 반올림 때문에 자주 다르다 — `4.97km` 이름 옆에
// `5`, `2.78km` 옆에 `2.8`.
//
// 어느 쪽이 진실인가는 이미 정해져 있다: **`km` 컬럼이 요금의 권위다** (T-KM, Sean 확정 —
// "의도적 코스 선택 시 코스 km이 권위"). 이름에 박힌 값은 빌더가 잰 생 길이라 요금과 다르다.
// 둘을 나란히 보여주면 사용자는 요금과 다른 숫자를 요금으로 읽는다.
//
// ⚠ 이건 **표시 계층의 보정이지 데이터가 옳아진 게 아니다** — `normalizeTrace()`와 같은 성격의
// 패치다. 진짜 해결은 인제스트가 이름에 길이를 넣지 않는 것이고, 그건 catalog 소유다.
// 데이터가 고쳐지면 이 함수는 아무것도 하지 않게 되고, 그때 지워도 안전하다.

/** 이름 **끝**에 붙은 길이 토큰만 떼어낸다. 가운데 있는 건 건드리지 않는다 —
 *  `반포 5km 코스`처럼 길이가 이름의 일부인 경우와, 꼬리표로 덧붙은 경우는 다르다. */
const TRAILING_KM = /[\s·・,-]*\d+(?:\.\d+)?\s*km$/i;

/**
 * 화면에 쓸 코스 이름. 길이는 옆 칸이 말하므로 이름은 이름만 말한다.
 * 떼고 나서 아무것도 남지 않으면(이름이 길이뿐이었다면) **원본을 그대로 돌려준다** —
 * 이름 없는 코스를 만드는 것보다 중복이 낫다.
 */
export function routeDisplayName(name: string | null | undefined): string {
  const raw = (name ?? '').trim();
  if (!raw) return raw;
  const stripped = raw.replace(TRAILING_KM, '').trim();
  return stripped.length > 0 ? stripped : raw;
}
