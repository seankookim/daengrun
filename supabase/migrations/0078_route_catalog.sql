-- 0078: 반포 프리메이드 코스 카탈로그 — 스키마 확장 + 반포 시드 9종
--
-- 결정 (Sean 2026-08-12, TODOS premade-route-catalog):
--   · 동네 단위 큐레이션 카탈로그, 반포 먼저. km 사이즈 루프 — 레벨 시스템은 폐기, km이 필터 키
--     (요청 화면 KmDial 1–10km × 0.5 스텝 → town 내 최근접 코스 + 불일치 배지, 기존 독트린 그대로).
--   · 코스 모델 = 3구간: 접근(커스터디, 무과금) → 루프(THE run, 과금 구간) → 귀가(커스터디, 동결).
--     구간은 부킹 런타임 개념 — 카탈로그 행은 루프 자체만 담는다 (앵커에서 출발, 앵커로 복귀).
--   · 코스별 메타데이터: 앵커(공통 만남점), 노면(발바닥 안전 — 기존 terrain), 그늘(여름 폭염),
--     조명(새벽/야간 슬롯), 실 GPS 트레이스(후속 — Course geo-traces TODO와 커플).
--
-- 정직 게이트:
--   · trace 는 전부 '[]' 시드 — 2026-08-06 정직성 배치가 목업 트레이스 폴백을 은퇴시켰다
--     ("목업 폴리라인을 코스 모양이라고 그리지 않는다"). 실 trace 는 파운더 워크(Sean이 GPS 켜고
--     직접 완주) 승격만이 유일한 경로. 그 전까지 지도 표면은 '준비 중'으로 어둡게 유지.
--   · checked_at null = 앱이 이미 '점검 예정'으로 렌더 (api.ts fmtChecked) — 워크 완료 시 기록.
--   · anchor_lat/lng 는 근사값 — 워크로 확정 전까지 앱 소비 금지 (현재 소비처 없음).
--     앵커 이름 + 사람용 디테일이 만남점의 진실이다.

alter table routes
  add column town text,                     -- 런치 타운 (요청 화면 필터 키) — area 는 사람이 읽는 위치 라벨
  add column anchor_name text,              -- 공통 만남점 (공원 정문, 나들목, 다리 입구)
  add column anchor_detail text,            -- 사람용 만남 디테일 ("매표소 앞 계단 아래")
  add column anchor_lat double precision,   -- 근사 — 파운더 워크 GPS 확정 전 소비 금지
  add column anchor_lng double precision,
  add column shade text check (shade in ('low','mid','high')),           -- 여름 그늘
  add column lighting text check (lighting in ('none','partial','lit')); -- 새벽/야간 조명

comment on column routes.terrain is '노면 = 발바닥 안전 축 (흙길/포장 비율) — 카탈로그 surface 역할';
comment on column routes.town is '런치 타운 스코프 — 요청 화면이 dialed km + town 으로 필터';

-- 기존 시드(성수 계열) 백필 — town 필터가 생겨도 좌초하지 않게
update routes set town = '성수동' where town is null;

-- 카탈로그 멱등 키 — 마이그레이션 재적용/시드 중복 방어
-- (settle 테스트 헬퍼는 town null 로 삽입 — null 은 서로 구별되어 무충돌)
create unique index routes_town_name_key on routes (town, name);

